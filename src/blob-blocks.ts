import { createHash, type Hash } from 'node:crypto';

import type { BlobBlock, DownloadBlobOptions } from './bs.ts';

// #############################################################################
// Block sizes
//
// A blob is cut into blocks at boundaries the content decides (FastCDC, with
// normalized chunking). A change inside a file moves only the boundaries next
// to it, so two versions of a file share every block the change did not touch
// — whether bytes were overwritten, inserted or removed.
//
// The sizes, the gear table and the masks below decide where every boundary
// falls. Changing any of them breaks nothing — a blob's id is the hash of its
// whole content, and a reader always follows the block list of the store it
// reads from — but blocks cut before the change are no longer shared with
// blocks cut after it.
// #############################################################################

/** The smallest block. Only the last block of a blob may be smaller. */
export const BLOCK_MIN_BYTES = 256 * 1024;

/** The block size the boundaries aim for. */
export const BLOCK_AVG_BYTES = 1024 * 1024;

/**
 * The largest block, and with it the largest message a blob ever needs.
 *
 * Far below a socket's message cap (Socket.IO's `maxHttpBufferSize`, 50 MB in
 * the hubs, 1 MB by default): a file of any size crosses as blocks, one
 * message each. Small enough that a store serving a block holds 4 MB, not a
 * file.
 */
export const BLOCK_MAX_BYTES = 4 * 1024 * 1024;

/** Characters of the base64url SHA256 digest that make an id. */
const _ID_LENGTH = 22;

// .............................................................................
/**
 * 256 fixed pseudo-random words, one per byte value, for the rolling hash.
 * Generated by xorshift32 from a fixed seed, so every store cuts the same
 * content at the same boundaries.
 */
const _gear: Uint32Array = (() => {
  const table = new Uint32Array(256);
  let x = 0x9e3779b9;
  for (let i = 0; i < table.length; i++) {
    x = (x ^ (x << 13)) >>> 0;
    x = (x ^ (x >>> 17)) >>> 0;
    x = (x ^ (x << 5)) >>> 0;
    table[i] = x;
  }
  return table;
})();

/**
 * 22 bits: a cut before {@link BLOCK_AVG_BYTES} is four times less likely
 * than one per {@link BLOCK_AVG_BYTES} bytes.
 */
const _maskBeforeAvg = 0xfffffc00;

/**
 * 18 bits: a cut after {@link BLOCK_AVG_BYTES} is four times more likely, so
 * block sizes cluster around the average.
 */
const _maskAfterAvg = 0xffffc000;

// .............................................................................
/**
 * Finds where the block starting at `start` ends.
 *
 * Deterministic in the bytes from `start` on: the same bytes give the same
 * end, wherever they sit in a blob. Call it with all bytes up to the blob's
 * end, or with at least {@link BLOCK_MAX_BYTES} of them — with fewer, the end
 * of the data would be taken for the end of the blob.
 * @param data - The bytes.
 * @param start - Where the block starts.
 * @param end - Where the data ends.
 * @returns The index after the block's last byte.
 */
export const blockEnd = (
  data: Uint8Array,
  start: number,
  end: number,
): number => {
  const length = end - start;
  if (length <= BLOCK_MIN_BYTES) return end;
  const barrier = start + Math.min(length, BLOCK_MAX_BYTES);
  const normal = Math.min(start + BLOCK_AVG_BYTES, barrier);

  let hash = 0;
  let i = start + BLOCK_MIN_BYTES;
  for (; i < normal; i++) {
    hash = ((hash << 1) + _gear[data[i]]) >>> 0;
    if ((hash & _maskBeforeAvg) === 0) return i + 1;
  }
  for (; i < barrier; i++) {
    hash = ((hash << 1) + _gear[data[i]]) >>> 0;
    if ((hash & _maskAfterAvg) === 0) return i + 1;
  }
  return barrier;
};

// #############################################################################
/**
 * The id of some bytes: SHA256 in base64url, cut to 22 characters — the same
 * id `@rljson/hash`'s `hshBuffer` gives, computed incrementally.
 */
export class ContentId {
  private readonly _hash: Hash = createHash('sha256');

  // ...........................................................................
  /**
   * Adds bytes to the content.
   * @param data - The next bytes.
   * @returns This, for chaining.
   */
  update(data: Uint8Array): this {
    this._hash.update(data);
    return this;
  }

  // ...........................................................................
  /**
   * The id of all bytes added so far. Call it once.
   * @returns The id.
   */
  digest(): string {
    return this._hash.digest('base64url').slice(0, _ID_LENGTH);
  }

  // ...........................................................................
  /**
   * The id of some bytes.
   * @param data - The bytes.
   * @returns The id.
   */
  static of(data: Uint8Array): string {
    return new ContentId().update(data).digest();
  }

  // ...........................................................................
  /**
   * An example with a few bytes added, for tests and docs.
   * @returns The example.
   */
  static example(): ContentId {
    return new ContentId().update(Buffer.from('example'));
  }
}

