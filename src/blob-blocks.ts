/**
 * A blob cut into blocks: its id, its size and its blocks.
 */
export interface BlobLayout {
  /** SHA256 hash of the whole content */
  blobId: string;
  /** Size in bytes */
  size: number;
  /** The blocks, in order */
  blocks: BlobBlock[];
}

/** Stores one block. */
export type PutBlock = (block: BlobBlock, bytes: Buffer) => Promise<void>;

/** Reads the bytes of one block. */
export type ReadBlock = (blockId: string) => Promise<Buffer>;

// .............................................................................
/**
 * Cuts content into blocks and hands each block to `putBlock`, one at a time.
 * @param content - A stream, a buffer or a string.
 * @param putBlock - Stores one block.
 * @returns The blob's id, size and blocks.
 */
export const writeBlocks = async (
  content: Buffer | string | ReadableStream<Uint8Array>,
  putBlock: PutBlock,
): Promise<BlobLayout> => {
  const whole = new ContentId();
  const blocks: BlobBlock[] = [];
  let size = 0;
  await forEachBlock(content, async (bytes) => {
    whole.update(bytes);
    const block: BlobBlock = {
      blockId: ContentId.of(bytes),
      size: bytes.length,
    };
    await putBlock(block, bytes);
    blocks.push(block);
    size += bytes.length;
  });
  return { blobId: whole.digest(), size, blocks };
};

// .............................................................................
/**
 * Fails unless `bytes` are the block `blockId`.
 * @param blockId - The block that was asked for.
 * @param bytes - What arrived.
 */
export const verifyBlock = (blockId: string, bytes: Uint8Array): void => {
  const actual = ContentId.of(bytes);
  if (actual !== blockId) {
    throw new Error(`Block '${blockId}' arrived as '${actual}'`);
  }
};

// .............................................................................
/**
 * Fails unless `blocks` hash to `blobId` together.
 * @param blobId - The blob the blocks claim to be.
 * @param blocks - The blocks, in order.
 * @param readBlock - Reads one block.
 * @returns The blob's size.
 */
export const verifyBlob = async (
  blobId: string,
  blocks: BlobBlock[],
  readBlock: ReadBlock,
): Promise<number> => {
  const whole = new ContentId();
  let size = 0;
  for (const { blockId } of blocks) {
    const bytes = await readBlock(blockId);
    whole.update(bytes);
    size += bytes.length;
  }
  const actual = whole.digest();
  if (actual !== blobId) {
    throw new Error(`Blocks of blob '${blobId}' make '${actual}'`);
  }
  return size;
};

// .............................................................................
/**
 * Reads a blob, or a range of it, from its blocks. Only the blocks the range
 * touches are read.
 * @param blocks - The blob's blocks, in order.
 * @param readBlock - Reads one block.
 * @param range - The bytes `[start, end)`; the whole blob when omitted.
 * @returns The bytes.
 */
export const readBlocks = async (
  blocks: BlobBlock[],
  readBlock: ReadBlock,
  range?: DownloadBlobOptions['range'],
): Promise<Buffer> => {
  const size = blocks.reduce((sum, block) => sum + block.size, 0);
  const start = range?.start ?? 0;
  const end = Math.min(range?.end ?? size, size);
  const parts: Buffer[] = [];
  let offset = 0;
  for (const block of blocks) {
    const first = offset;
    offset += block.size;
    if (offset <= start) continue;
    if (first >= end) break;
    const bytes = await readBlock(block.blockId);
    parts.push(
      bytes.subarray(Math.max(start - first, 0), Math.min(end, offset) - first),
    );
  }
  return Buffer.concat(parts);
};

// .............................................................................
/**
 * Streams a blob from its blocks, one block at a time, and fails the stream
 * at its end unless the bytes hash to `blobId`.
 * @param blobId - The blob.
 * @param blocks - Its blocks, in order.
 * @param readBlock - Reads one block.
 * @param onComplete - Called once every byte was read and verified, before
 * the stream closes.
 * @returns The stream.
 */
export const streamBlocks = (
  blobId: string,
  blocks: BlobBlock[],
  readBlock: ReadBlock,
  onComplete?: () => Promise<void>,
): ReadableStream<Uint8Array> => {
  const whole = new ContentId();
  let index = 0;
  return new ReadableStream<Uint8Array>({
    pull: async (controller) => {
      if (index === blocks.length) {
        const actual = whole.digest();
        if (actual !== blobId) {
          throw new Error(`Blocks of blob '${blobId}' make '${actual}'`);
        }
        await onComplete?.();
        controller.close();
        return;
      }
      const bytes = await readBlock(blocks[index++].blockId);
      whole.update(bytes);
      controller.enqueue(
        new Uint8Array(bytes.buffer, bytes.byteOffset, bytes.length),
      );
    },
  });
};
