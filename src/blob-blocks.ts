/**
 * Hands out the pieces of some content, one at a time, as they arrive.
 * @param content - A stream, a buffer or a string.
 * @param onPiece - Takes one piece.
 */
const _forEachPiece = async (
  content: Buffer | string | ReadableStream<Uint8Array>,
  onPiece: (piece: Uint8Array) => Promise<void>,
): Promise<void> => {
  if (typeof content === 'string') {
    return onPiece(Buffer.from(content, 'utf8'));
  }
  if (Buffer.isBuffer(content)) {
    return onPiece(content);
  }
  const reader = content.getReader();
  try {
    for (;;) {
      const { done, value } = await reader.read();
      if (done) return;
      await onPiece(value);
    }
  } finally {
    reader.releaseLock();
  }
};

// .............................................................................
/**
 * Cuts the blocks off the front of `data`: every block when `final`, else
 * as long as {@link BLOCK_MAX_BYTES} remain, so a cut never mistakes the end
 * of the data for the end of the content.
 * @param data - The bytes.
 * @param final - Whether the content ends with `data`.
 * @param onBlock - Takes one block.
 * @returns Where the bytes not cut yet begin.
 */
const _cutBlocks = async (
  data: Buffer,
  final: boolean,
  onBlock: (bytes: Buffer) => Promise<void>,
): Promise<number> => {
  let start = 0;
  while (data.length - start >= (final ? 1 : BLOCK_MAX_BYTES)) {
    const end = blockEnd(data, start, data.length);
    await onBlock(data.subarray(start, end));
    start = end;
  }
  return start;
};

// .............................................................................
/**
 * Cuts content into blocks and hands them out, one at a time, in order.
 *
 * Holds at most one {@link BLOCK_MAX_BYTES} block plus one incoming piece of a
 * stream, whatever the content's size. A buffer or a string is cut where it
 * lies, without a copy. A block is a view into a buffer that is only held
 * until `onBlock` resolves: copy it to keep it.
 * @param content - A stream, a buffer or a string.
 * @param onBlock - Takes one block.
 */
export const forEachBlock = async (
  content: Buffer | string | ReadableStream<Uint8Array>,
  onBlock: (bytes: Buffer) => Promise<void>,
): Promise<void> => {
  let pieces: Uint8Array[] = [];
  let buffered = 0;
  await _forEachPiece(content, async (piece) => {
    pieces.push(piece);
    buffered += piece.length;
    if (buffered < BLOCK_MAX_BYTES) return;

    const data =
      pieces.length === 1
        ? Buffer.from(piece.buffer, piece.byteOffset, piece.length)
        : Buffer.concat(pieces, buffered);
    const start = await _cutBlocks(data, false, onBlock);
    pieces = start < data.length ? [data.subarray(start)] : [];
    buffered = data.length - start;
  });
  await _cutBlocks(Buffer.concat(pieces, buffered), true, onBlock);
};

